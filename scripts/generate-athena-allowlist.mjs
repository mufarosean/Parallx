// generate-athena-allowlist.mjs — regenerate the Athena function allowlist (M99).
//
// Parses Pearson's authoritative "Athena Spreadsheet Function Comparison"
// workbook (docs/research/assets/cas-pearson/, downloaded from pearsonvue.com
// — URL in docs/research/CAS_Pearson_Spreadsheet_Environment.md) into
// src/built-in/worksheet/athenaFunctions.json. Column layout (Functions
// sheet): [0] category, [2] the Pearson VUE test driver's function name —
// a real name when supported, a dash marker when not.
//
// Run manually when Pearson updates the workbook:
//   node scripts/generate-athena-allowlist.mjs

import { createRequire } from 'node:module';
import { writeFileSync } from 'node:fs';

const require = createRequire(import.meta.url);
const XLSX = require('xlsx');

const SOURCE = 'docs/research/assets/cas-pearson/Athena-Spreadsheet-Function-Comparison.xlsx';
const TARGET = 'src/built-in/worksheet/athenaFunctions.ts';

const wb = XLSX.readFile(SOURCE);
const ws = wb.Sheets['Functions'];
if (!ws) throw new Error(`"Functions" sheet not found — sheets: ${wb.SheetNames.join(', ')}`);

const rows = XLSX.utils.sheet_to_json(ws, { header: 1 });
const functions = new Set();
for (const row of rows.slice(1)) {
  const name = String(row?.[2] ?? '').trim();
  // Dash markers ("-------") flag unsupported entries; skip headers/blanks too.
  if (!name || name.startsWith('---') || !/^[A-Z][A-Z0-9._]*$/i.test(name)) continue;
  functions.add(name.toUpperCase());
}

if (functions.size < 200) {
  throw new Error(`Only ${functions.size} functions parsed — the workbook layout likely changed; refusing to write a bogus allowlist.`);
}

const sorted = [...functions].sort();
const body = [
  '// athenaFunctions.ts — GENERATED by scripts/generate-athena-allowlist.mjs.',
  '// Do not edit by hand; regenerate from the Pearson workbook instead.',
  `// Source: Pearson VUE "Athena Spreadsheet Function Comparison" (generated ${new Date().toISOString().slice(0, 10)};`,
  '// see docs/research/CAS_Pearson_Spreadsheet_Environment.md for the URL).',
  '',
  '/** Spreadsheet functions available on the Pearson Athena exam driver. */',
  'export const ATHENA_FUNCTIONS: readonly string[] = [',
  ...sorted.map((f) => `  '${f}',`),
  '];',
  '',
].join('\n');

writeFileSync(TARGET, body);
console.log(`Wrote ${functions.size} Athena-supported functions to ${TARGET}`);
